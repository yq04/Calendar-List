import assert from "node:assert/strict";
import { createDraftSessions, bindImeGuard, isImeComposing } from "./src/input-session.js";
const drafts = createDraftSessions();
drafts.update("2026-10-15", "首条");
const first = drafts.snapshot("2026-10-15");
drafts.update("2026-10-15", "下一条");
assert.equal(drafts.acknowledge(first), false);
assert.equal(drafts.get("2026-10-15").text, "下一条");
drafts.update("2026-10-16", "另一天");
assert.equal(drafts.get("2026-10-15").text, "下一条");
assert.equal(drafts.get("2026-10-16").text, "另一天");
const oldSession = drafts.snapshot("2026-10-16");
drafts.cancel("2026-10-16");
drafts.update("2026-10-16", "另一天");
assert.equal(drafts.acknowledge(oldSession), false, "same text in a new session cannot acknowledge an old write");
assert.equal(drafts.acknowledge(drafts.snapshot("2026-10-16")), true);
const input = new EventTarget();
bindImeGuard(input);
input.dispatchEvent(new Event("compositionstart"));
assert.equal(isImeComposing(null, input), true);
const enter = new Event("keydown");Object.defineProperty(enter, "key", { value: "Enter" });
input.dispatchEvent(enter);
input.dispatchEvent(new Event("compositionend"));
assert.equal(isImeComposing(null, input), true, "candidate confirmation stays guarded until key release");
input.dispatchEvent(new Event("keyup"));
assert.equal(isImeComposing(null, input), false);
assert.equal(isImeComposing({keyCode:229}), true);
console.log("input sessions: revision, date, replaced session, single acknowledgement and composition release passed");
